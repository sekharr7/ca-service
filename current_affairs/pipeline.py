import asyncio
import random
import time
from datetime import date, datetime
from urllib.parse import urlparse
from sqlalchemy import orm

from concurrent.futures import ThreadPoolExecutor
from crawl4ai import AsyncWebCrawler

from current_affairs.crawler import fetch_article, preprocess_url, _is_blocked_response, check_unsupported_url
from current_affairs.synthesizer import (
    build_system_prompt,
    generate_content,
    clean_and_format_markdown,
    split_markdown_sections,
)
from current_affairs.classifier import classify_topic_subtopic
from current_affairs.config import IMAGE_CONCURRENCY
from current_affairs.image_generator import generate_and_save_image
from current_affairs.validator import is_error_page_title, is_dummy_content
from current_affairs.database import CurrentAffair, Highlight, Image, Keyword


_DEFAULT_IMAGE_SEMAPHORE: asyncio.Semaphore | None = None


def get_default_image_semaphore() -> asyncio.Semaphore:
    global _DEFAULT_IMAGE_SEMAPHORE
    if _DEFAULT_IMAGE_SEMAPHORE is None:
        _DEFAULT_IMAGE_SEMAPHORE = asyncio.Semaphore(IMAGE_CONCURRENCY)
    return _DEFAULT_IMAGE_SEMAPHORE


async def process_article_service(
    ca_created_date: str | datetime | date,
    theme: str,
    article_url: str,
    db: orm.Session,
    theme_topic: str | None = None,
    theme_subtopic: str | None = None,
    wait_for_image: bool = False,
    crawler: AsyncWebCrawler | None = None,
    image_executor: ThreadPoolExecutor | None = None,
    image_semaphore: asyncio.Semaphore | None = None,
) -> dict:
    """
    Process a single article:
    1. Preprocesses and canonicalizes URL.
    2. Validates against unsupported media/e-paper links.
    3. Crawls raw article text using site-specific or markdown scrapers.
       - STRICT FAIL-CLOSED: If scraping fails or body < 300 chars, aborts immediately.
       - NEVER produces synthetic hallucinations or generates images for unextracted articles.
    4. Synthesizes UPSC-formatted notes via Perplexity.
    5. Validates generated title, subtitle, and content against dummy/error markers.
    6. Classifies missing theme_topic/subtopic against DB taxonomy.
    7. Stores article records in development DB (mntor_dev).
    8. Dispatches infographic image generation ONLY when extraction & validation succeed.
    """
    t_row_start = time.time()

    # 1. Fetch article
    processed_url = preprocess_url(article_url)

    unsupported_err = check_unsupported_url(processed_url)
    if unsupported_err:
        raise ValueError(f"Unsupported URL: {unsupported_err}")

    domain = urlparse(processed_url).netloc
    prompt = f"news article from {domain} current affairs"
    t_scrape = time.time()
    
    article_text = ""
    try:
        article_text = await fetch_article(processed_url, prompt, crawler=crawler)
        scrape_duration = round(time.time() - t_scrape, 1)
        print(f"[SCRAPE] Extracted {len(article_text)} chars in {scrape_duration}s", flush=True)
    except Exception as scrape_err:
        print(f"[SCRAPE] Crawl failed for {processed_url} ({scrape_err})", flush=True)
        raise ValueError(f"Scraping failed for {processed_url}: {scrape_err}")

    # Strict Fail-Closed Gate: Require >= 300 characters of real text
    if not article_text or len(article_text.strip()) < 300 or _is_blocked_response(article_text):
        chars_count = len(article_text.strip()) if article_text else 0
        raise ValueError(
            f"Extraction failed or insufficient article content ({chars_count} chars) for URL: {processed_url}. "
            f"Halting pipeline: no synthetic hallucination or image generation will be performed."
        )

    # 2. Synthesize UPSC educational notes
    system_prompt = build_system_prompt()
    t_llm = time.time()
    generated_content = generate_content(article_text, system_prompt)
    llm_duration = round(time.time() - t_llm, 1)

    if not generated_content:
        raise ValueError("No content generated by LLM")

    clean_content = clean_and_format_markdown(generated_content)
    title, subtitle, rest_content, keywords = split_markdown_sections(clean_content)
    print(f"Keywords: {keywords}", flush=True)

    # Validate extracted title and content to prevent error/dummy pages from entering the DB or triggering image generation
    if not title or len(title.strip()) < 10 or is_error_page_title(title):
        raise ValueError(f"Generated content has invalid or error title: '{title}'")

    if not subtitle or len(subtitle.strip()) < 20 or is_dummy_content(subtitle):
        raise ValueError(f"Generated content has invalid or dummy subtitle: '{subtitle}'")

    if is_dummy_content(title) or is_dummy_content(rest_content[:400]):
        raise ValueError(f"Content not identified / placeholder output: '{title}'")

    # 3. Classify missing theme_topic or theme_subtopic against mtr_topics/mtr_subtopics
    t_tax = time.time()
    if not theme_topic or not theme_subtopic or str(theme_topic).strip() == "" or str(theme_subtopic).strip() == "":
        print(f"[TAXONOMY] Classifying missing topic/subtopic against mtr_topics/mtr_subtopics using gpt-6-luna...", flush=True)
        detected_topic, detected_subtopic = classify_topic_subtopic(
            db=db,
            theme=theme,
            title=title,
            subtitle=subtitle,
            keywords=keywords,
            existing_topic=theme_topic,
        )
        if (not theme_topic or str(theme_topic).strip() == "") and detected_topic:
            theme_topic = detected_topic
            print(f"[TAXONOMY] Assigned theme_topic: '{theme_topic}'", flush=True)
        if (not theme_subtopic or str(theme_subtopic).strip() == "") and detected_subtopic:
            theme_subtopic = detected_subtopic
            print(f"[TAXONOMY] Assigned theme_subtopic: '{theme_subtopic}'", flush=True)
        tax_duration = round(time.time() - t_tax, 2)
    else:
        tax_duration = 0.0

    # 4. Parse date strictly from the date specified in the file
    if isinstance(ca_created_date, (datetime, date)):
        parsed_date = datetime(ca_created_date.year, ca_created_date.month, ca_created_date.day)
    elif isinstance(ca_created_date, str) and ca_created_date.strip():
        for fmt in ("%d-%m-%Y", "%Y-%m-%d", "%d/%m/%Y", "%Y/%m/%d"):
            try:
                parsed_date = datetime.strptime(ca_created_date.strip(), fmt)
                break
            except ValueError:
                pass
        else:
            raise ValueError(f"Could not parse date from file: '{ca_created_date}'")
    else:
        raise ValueError(f"Missing date in file for this article (got {repr(ca_created_date)})")

    # ca_created_date and created_at strictly follow the file's specified date
    created_at = parsed_date.replace(hour=16, minute=7, second=7)

    # 5. Database staging and commit
    t_db = time.time()
    ca_entry = CurrentAffair(
        topic=title,
        content=subtitle,
        theme=theme,
        theme_topic=theme_topic,
        theme_subtopic=theme_subtopic,
        ca_created_date=parsed_date,
        created_at=created_at,
        source=processed_url,
        view_count=random.randint(7, 56),
    )
    db.add(ca_entry)
    db.flush()

    highlight = Highlight(
        id=ca_entry.id,
        current_affair_id=ca_entry.id,
        highlight_text=rest_content,
        created_at=created_at,
    )
    db.add(highlight)

    image_url = f"https://yookicaimages.blob.core.windows.net/thumbnail/{ca_entry.id}.jpg"
    db.add(Image(
        id=ca_entry.id,
        current_affair_id=ca_entry.id,
        image_url=image_url,
        created_at=created_at,
    ))

    db.add(Keyword(
        id=ca_entry.id,
        current_affair_id=ca_entry.id,
        kword=keywords,
    ))

    db.commit()
    db_duration = round(time.time() - t_db, 2)
    print(f"[DB] Article record {ca_entry.id} committed successfully in {db_duration}s", flush=True)

    # 6. Image generation (parallel async task or synchronous wait)
    image_task = None
    if wait_for_image:
        print(f"[IMAGE] Generating and uploading image for article {ca_entry.id}...", flush=True)
        await asyncio.to_thread(
            generate_and_save_image,
            ca_entry.id,
            title,
            subtitle,
        )
    else:
        print(f"[IMAGE] Enqueuing background image task for article {ca_entry.id}...", flush=True)
        if image_semaphore is not None:
            async def _generate_throttled():
                async with image_semaphore:
                    return await asyncio.to_thread(generate_and_save_image, ca_entry.id, title, subtitle)

            image_task = asyncio.create_task(_generate_throttled(), name=f"img_task_{ca_entry.id}")
        elif image_executor is not None:
            # Submits to thread pool if executor provided
            cf_future = image_executor.submit(generate_and_save_image, ca_entry.id, title, subtitle)
            image_task = asyncio.wrap_future(cf_future)
        else:
            async def _generate_throttled_default():
                sem = get_default_image_semaphore()
                async with sem:
                    return await asyncio.to_thread(generate_and_save_image, ca_entry.id, title, subtitle)

            image_task = asyncio.create_task(_generate_throttled_default(), name=f"img_task_{ca_entry.id}")

    total_article_duration = round(time.time() - t_row_start, 2)
    print(
        f"[TIMING] Article {ca_entry.id} completed in {total_article_duration}s "
        f"[Scrape: {scrape_duration}s | Synthesis: {llm_duration}s | Taxonomy: {tax_duration}s | DB: {db_duration}s]",
        flush=True,
    )

    return {
        "id": ca_entry.id,
        "topic": title,
        "theme_topic": theme_topic,
        "theme_subtopic": theme_subtopic,
        "markdown": clean_content,
        "images": [image_url],
        "image_task": image_task,
        "timings": {
            "scrape": scrape_duration,
            "synthesis": llm_duration,
            "taxonomy": tax_duration,
            "db": db_duration,
            "total": total_article_duration,
        },
    }
